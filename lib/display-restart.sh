# shellcheck shell=bash
# lib/display-restart.sh - opt-in display restart behind a dead-man's switch.
#
# Restarting the agent's display is the one step that can lock the agent out of
# its own desktop, so it only runs with --apply --restart-displays and
# DISPLAY_RESTART_MODE=kill (a supervisor is expected to relaunch a killed
# Xvfb through the hardened wrapper). Before the restart a detached timer is
# armed; only an end-to-end X check afterwards writes the canary that stands it
# down. If the check never passes, the timer puts the display back on -ac.

restart_display() {
	local n="$1" pid rb canary i ok=0
	[ "${DISPLAY_RESTART_MODE}" = kill ] ||
		{ MSG="DISPLAY_RESTART_MODE=${DISPLAY_RESTART_MODE}: restart :${n} yourself (or set kill if a supervisor restarts Xvfb)"; return 1; }
	CUR_N="${n}"
	c2b_cookie || { MSG="cookie not ready: ${MSG}"; return 1; }
	mkdir -p "${STATE_DIR}" && chmod 700 "${STATE_DIR}"
	rb="${STATE_DIR}/rollback-d${n}.sh"
	canary="/run/box-hardening-xauth-${n}.ok"
	rm -f "${canary}"
	cat >"${rb}" <<ROLLBACK
#!/usr/bin/env bash
# Generated by box-hardening.sh: return :${n} to -ac if the canary never appeared.
echo "\$(date '+%F %T %Z') rollback :${n} start" >>"${LOG_FILE}"
mkdir -p "${XVFB_NOAUTH_DIR}" && touch "${XVFB_NOAUTH_DIR}/noauth-${n}"
rm -f "${XAUTH_SRV_PREFIX}${n}"
runuser -u "${AGENT_USER}" -- xauth -q -f "${AGENT_XAUTH}" remove ":${n}" >/dev/null 2>&1 || true
pkill -f '^Xvfb :${n} .*-auth' && echo "killed authed Xvfb :${n}; the supervisor relaunches it with -ac (remove ${XVFB_NOAUTH_DIR}/noauth-${n} to re-enable)" >>"${LOG_FILE}"
echo "\$(date '+%F %T %Z') rollback :${n} done" >>"${LOG_FILE}"
ROLLBACK
	chmod 700 "${rb}"
	# shellcheck disable=SC2016  # the positional parameters belong to the inner bash
	setsid nohup bash -c 'sleep "$1"; if [ -e "$2" ]; then echo "$(date "+%F %T %Z") canary $2 present, standing down" >>"$4"; else bash "$3"; fi' \
		_ "${DMS_SECONDS}" "${canary}" "${rb}" "${LOG_FILE}" >/dev/null 2>&1 </dev/null &
	log "2B :${n} dead-man's switch armed (${DMS_SECONDS}s, canary ${canary}, rollback ${rb})"
	pid="$(xvfb_pid "${n}")"
	[ -z "${pid}" ] || kill "${pid}" 2>/dev/null || true
	for i in $(seq 1 60); do [ "$(xvfb_mode "${n}")" = auth ] && break; sleep 0.5; done
	for i in $(seq 1 40); do
		if [ "$(xvfb_mode "${n}")" = auth ] && x_connect "${AGENT_USER}" "${AGENT_XAUTH}" "${n}" &&
			! x_connect "${AGENT_USER}" /dev/null "${n}"; then
			if [ "${n}" = "${BROWSER_DISPLAY}" ]; then
				x_connect "${BROWSER_USER}" "${BROWSER_XAUTH}" "${n}" && { ok=1; break; }
			elif ! x_connect "${BROWSER_USER}" "${BROWSER_XAUTH}" "${n}"; then
				ok=1; break
			fi
		fi
		sleep 0.5
	done
	if [ "${ok}" -eq 1 ]; then
		touch "${canary}"
		log "2B :${n} end-to-end check passed; canary written, timer will stand down"
		return 0
	fi
	MSG="end-to-end check failed after restart; rollback fires in ${DMS_SECONDS}s unless ${canary} is created"
	return 1
}

section_2b() {
	local n list
	log "== Section 2 Part B: X display cookie auth =="
	targets_step 2B
	list="$(x_display_list)"
	[ -n "${list}" ] || record 2B "running displays" SKIP "no Xvfb running"
	for n in ${list}; do CUR_N="${n}"; step 2B ":${n} cookie (server + agent)" c2b_cookie f2b_cookie; done
	if [ -n "$(xvfb_pid "${BROWSER_DISPLAY}")" ] || [ -f "${XAUTH_SRV_PREFIX}${BROWSER_DISPLAY}" ]; then
		step 2B ":${BROWSER_DISPLAY} cookie for the browser user only" c2b_browser f2b_browser
	else
		record 2B ":${BROWSER_DISPLAY} cookie for the browser user only" SKIP ":${BROWSER_DISPLAY} not running and no server cookie yet"
	fi
	for n in ${list}; do CUR_N="${n}"; step 2B ":${n} Xvfb running with cookie auth" c2b_live f2b_live; done
	if [ -s "${XVFB_AUTH_LOG}" ] && grep -q WARNING "${XVFB_AUTH_LOG}"; then
		record 2B "wrapper fail-safe log" WARN "$(grep -c WARNING "${XVFB_AUTH_LOG}") WARNING line(s) in ${XVFB_AUTH_LOG} (a display fell back to -ac at some point)"
	fi
}
